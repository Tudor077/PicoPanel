package com.picopanel.pocket;

/**
 * A 128x32 one-bit framebuffer in SSD1306 page order, plus the 5x7 font the
 * panel draws with. Pure Java: no android.* here, so the emulator's screen can
 * be rendered and checked on a JVM.
 */
public final class Screen {

    /** 5 columns per glyph, one byte each, bit 0 = top row. */
    private static final String GLYPH_KEYS = " !%*+-./0123456789:?ABCDEFGHIJKLMNOPQRSTUVWXYZ";
    private static final int[][] GLYPHS = {
        {0x00,0x00,0x00,0x00,0x00}, {0x00,0x00,0x5F,0x00,0x00}, {0x23,0x13,0x08,0x64,0x62},
        {0x14,0x08,0x3E,0x08,0x14}, {0x08,0x08,0x3E,0x08,0x08}, {0x08,0x08,0x08,0x08,0x08},
        {0x00,0x60,0x60,0x00,0x00}, {0x20,0x10,0x08,0x04,0x02}, {0x3E,0x51,0x49,0x45,0x3E},
        {0x00,0x42,0x7F,0x40,0x00}, {0x42,0x61,0x51,0x49,0x46}, {0x21,0x41,0x45,0x4B,0x31},
        {0x18,0x14,0x12,0x7F,0x10}, {0x27,0x45,0x45,0x45,0x39}, {0x3C,0x4A,0x49,0x49,0x30},
        {0x01,0x71,0x09,0x05,0x03}, {0x36,0x49,0x49,0x49,0x36}, {0x06,0x49,0x49,0x29,0x1E},
        {0x00,0x36,0x36,0x00,0x00}, {0x02,0x01,0x51,0x09,0x06}, {0x7E,0x11,0x11,0x11,0x7E},
        {0x7F,0x49,0x49,0x49,0x36}, {0x3E,0x41,0x41,0x41,0x22}, {0x7F,0x41,0x41,0x22,0x1C},
        {0x7F,0x49,0x49,0x49,0x41}, {0x7F,0x09,0x09,0x01,0x01}, {0x3E,0x41,0x49,0x49,0x7A},
        {0x7F,0x08,0x08,0x08,0x7F}, {0x00,0x41,0x7F,0x41,0x00}, {0x20,0x40,0x41,0x3F,0x01},
        {0x7F,0x08,0x14,0x22,0x41}, {0x7F,0x40,0x40,0x40,0x40}, {0x7F,0x02,0x04,0x02,0x7F},
        {0x7F,0x04,0x08,0x10,0x7F}, {0x3E,0x41,0x41,0x41,0x3E}, {0x7F,0x09,0x09,0x09,0x06},
        {0x3E,0x41,0x51,0x21,0x5E}, {0x7F,0x09,0x19,0x29,0x46}, {0x46,0x49,0x49,0x49,0x31},
        {0x01,0x01,0x7F,0x01,0x01}, {0x3F,0x40,0x40,0x40,0x3F}, {0x1F,0x20,0x40,0x20,0x1F},
        {0x7F,0x20,0x18,0x20,0x7F}, {0x63,0x14,0x08,0x14,0x63}, {0x03,0x04,0x78,0x04,0x03},
        {0x61,0x51,0x49,0x45,0x43}
    };

    public final int width, height;
    public final byte[] buf;

    public Screen(int w, int h) { width = w; height = h; buf = new byte[w * h / 8]; }
    public Screen() { this(128, 32); }

    public void clear() { java.util.Arrays.fill(buf, (byte) 0); }

    public void pixel(int x, int y) {
        if (x < 0 || y < 0 || x >= width || y >= height) return;
        buf[x + (y >> 3) * width] |= (byte) (1 << (y & 7));
    }

    public boolean get(int x, int y) {
        if (x < 0 || y < 0 || x >= width || y >= height) return false;
        return (buf[x + (y >> 3) * width] & (1 << (y & 7))) != 0;
    }

    public void text(int x, int y, String s) {
        String up = s.toUpperCase(java.util.Locale.ROOT);
        for (int i = 0; i < up.length(); i++) {
            int gi = GLYPH_KEYS.indexOf(up.charAt(i));
            if (gi >= 0) {
                int[] g = GLYPHS[gi];
                for (int c = 0; c < 5; c++)
                    for (int r = 0; r < 7; r++)
                        if ((g[c] & (1 << r)) != 0) pixel(x + c, y + r);
            }
            x += 6;
            if (x >= width) break;
        }
    }

    public void rect(int x, int y, int w, int h, boolean fill) {
        for (int dx = 0; dx < w; dx++)
            for (int dy = 0; dy < h; dy++) {
                boolean edge = dx == 0 || dx == w - 1 || dy == 0 || dy == h - 1;
                if (fill || edge) pixel(x + dx, y + dy);
            }
    }

    /** The screen as text, for tests and for looking at it in a terminal. */
    public String toArt() {
        StringBuilder sb = new StringBuilder();
        for (int y = 0; y < height; y++) {
            for (int x = 0; x < width; x++) sb.append(get(x, y) ? '#' : '.');
            if (y < height - 1) sb.append('\n');
        }
        return sb.toString();
    }
}
